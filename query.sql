WITH
	MCCP AS (
		SELECT DISTINCT
			CPLN_ST_DT,
			CPLN_END_DT,
			CYCLE_PLAN.CNTRY_NK,
			CYCLE_PLAN.SLSA_NK,
			CYCLE_PLAN_TARGET.HCP_SK
		FROM
			COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_HCP_INTERACTION_REPOSITORY.CYCLE_PLAN
			INNER JOIN COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_HCP_INTERACTION_REPOSITORY.CYCLE_PLAN_TARGET ON CYCLE_PLAN.CPLN_SK = CYCLE_PLAN_TARGET.CPLN_SK
		WHERE
			CYCLE_PLAN.CNTRY_NK IN  (
            'SI', 'HR', 'RS', 'BA', 'EE',
            'LV', 'LT', 'BG', 'UA', 'KZ'
        )
			AND CYCLE_PLAN.CPLN_ST_DT >= '2024-12-01'
			AND CYCLE_PLAN.ACTIVE = 'Y'
			AND CYCLE_PLAN_TARGET.ACTIVE = 'Y'
			AND CYCLE_PLAN.CPLN_MCCP_FLG = 'Y'
			AND CYCLE_PLAN_TARGET.CPTG_TYP = 'PERSON'
			--AND CYCLE_PLAN_TARGET.CPTG_TRGT_GOAL > 0
			AND CPLN_CYCLE_NM NOT LIKE '%UPJ%'
			AND CPLN_TEAM NOT LIKE '%UPJ%'
			AND CPLN_TERRITORY NOT LIKE '%UPJ%'
	),
	BRANDS_WITH_DSP AS (
		SELECT DISTINCT
			CLM_PRESENTATION_BUSINESS_RULE.CNTRY_NK,
			CLM_PRESENTATION.PRDX_NK
		FROM
			COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_HCP_INTERACTION_REPOSITORY.CLM_PRESENTATION_BUSINESS_RULE
			INNER JOIN COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_HCP_INTERACTION_REPOSITORY.CLM_PRESENTATION ON CLM_PRESENTATION_BUSINESS_RULE.CLMP_SK = CLM_PRESENTATION.CLMP_SK
			AND CLM_PRESENTATION_BUSINESS_RULE.CNTRY_NK = CLM_PRESENTATION.CNTRY_NK
			AND CLM_PRESENTATION_BUSINESS_RULE.ACTIVE = 'Y'
		WHERE
			CLM_PRESENTATION_BUSINESS_RULE.CNTRY_NK  IN (
            'SI', 'HR', 'RS', 'BA', 'EE',
            'LV', 'LT', 'BG', 'UA', 'KZ'
        )
	)
SELECT
    DISTINCT
	COUNTRY.CNTR_CLUSTER AS MARKET_CD,
	CEM_XCHANNEL_INTERACTIONS.INTR_MNTH,
	INTERACTION_CALL.INCL_CALL_NM,
	LEFT(INCL_CALL_NM,1) AS CALL_EVENT,
	INTERACTION_CALL.INCL_RMT_CHNL,
	INTERACTION_CALL.INCL_SRC_SUBTYP,
	INTERACTION_CALL.INCL_SRC_TYP,
	INTERACTION_CALL.INCL_VCC_FLG,
	INTERACTION_CALL.INCL_EVENT_TYP,
    INTERACTION_CALL.INCL_DT,
	INTERACTION_CALL.INCL_COACHING_VISIT_FLG,
	SALES_FORCE.SLSF_DESC,
	SALES_AREA.SLSA_NK,
	CEM_XCHANNEL_INTERACTIONS.EMPL_SK AS CALL_OWNER_SK,
	CEM_XCHANNEL_INTERACTIONS.GLOBAL_CALL_TYPE,
	CEM_XCHANNEL_INTERACTIONS.IS_VCC_FLAG,
    CEM_XCHANNEL_INTERACTIONS.IS_CLM_FLAG,
	CEM_XCHANNEL_INTERACTIONS.PFBR_NM,
	CEM_XCHANNEL_INTERACTIONS.PFBR_GLOBAL_PFIZER_BRAND_NM,
	PRODUCT_XREF.PRDX_NM,
	CASE
		WHEN CEM_XCHANNEL_INTERACTIONS.GLOBAL_ACTIVITY_TYPE = 'DETAIL CALL' THEN 'F2F'
		WHEN CEM_XCHANNEL_INTERACTIONS.GLOBAL_ACTIVITY_TYPE = 'CLICKED' THEN 'RTE CLICKED'
		ELSE CEM_XCHANNEL_INTERACTIONS.GLOBAL_ACTIVITY_TYPE
	END AS GLOBAL_ACTIVITY_TYPE,
	CASE WHEN LEFT(INTERACTION_CALL.INCL_CALL_NM,1)='E' THEN INTERACTION_CALL.INCL_CALL_NM ELSE NULL END AS EVENTS,
	CASE WHEN LEFT(INTERACTION_CALL.INCL_CALL_NM,1)='C' AND INTERACTION_CALL.INCL_SUBTYP <> 'Unplanned' AND INTERACTION_CALL.INCL_COACHING_VISIT_FLG <> 'Y' THEN INTERACTION_CALL.INCL_CALL_NM ELSE NULL END AS CALLS,
	CASE WHEN INTERACTION_CALL.INCL_HCP_CNT > 0 AND INTERACTION_CALL.INCL_TYP IN ('Detail Call') THEN CEM_XCHANNEL_INTERACTIONS.IHCL_NK ELSE NULL END AS ENGAGEMENTS,
	CASE WHEN INTERACTION_CALL.INCL_HCP_CNT > 0  THEN CEM_XCHANNEL_INTERACTIONS.IHCL_NK ELSE NULL END  AS ACTIVITIES,
	CASE
			 WHEN MCCP.HCP_SK IS NOT NULL  AND INTERACTION_CALL.INCL_HCP_CNT > 0 AND INTERACTION_CALL.INCL_TYP IN ('Detail Call') THEN CEM_XCHANNEL_INTERACTIONS.IHCL_NK
			ELSE NULL
		END
	AS ENGAGEMENTS_TO_TARGET,
	CASE WHEN MCCP.HCP_SK IS NOT NULL  AND LEFT(INTERACTION_CALL.INCL_CALL_NM,1)='C' AND INTERACTION_CALL.INCL_SUBTYP <> 'Unplanned' AND INTERACTION_CALL.INCL_COACHING_VISIT_FLG <> 'Y' THEN INTERACTION_CALL.INCL_CALL_NM ELSE NULL END AS CALLS_TO_TARGET,
	CASE 
            WHEN INTERACTION_CALL.INCL_HCP_CNT > 0 OR CEM_XCHANNEL_INTERACTIONS.GLOBAL_CALL_TYPE ='REP TRIGGERED EMAIL' THEN CEM_XCHANNEL_INTERACTIONS.INTR_ENGAG_ID
            ELSE NULL
        END
    AS INTERACTIONS,
	CASE WHEN CEM_XCHANNEL_INTERACTIONS.SRC_ACTIVITY_TYPE ='Detail Call' AND INTERACTION_CALL.INCL_HCP_CNT > 0 THEN CEM_XCHANNEL_INTERACTIONS.INTR_ENGAG_ID ELSE NULL END AS INTERACTIONS_DETAIL_CALL,
	CASE
			WHEN CEM_XCHANNEL_INTERACTIONS.GLOBAL_CALL_TYPE IN ('VIRTUAL DETAIL', 'FACE TO FACE')
			AND CEM_XCHANNEL_INTERACTIONS.GLOBAL_ACTIVITY_TYPE <> 'PHONE CALL' 
            THEN CEM_XCHANNEL_INTERACTIONS.INTR_ENGAG_ID
			ELSE NULL
		END
	AS INTERACTIONS_NO_PHONECALL,
	CASE
			WHEN CEM_XCHANNEL_INTERACTIONS.IS_CLM_FLAG = 'Y'
			AND CEM_XCHANNEL_INTERACTIONS.GLOBAL_CALL_TYPE IN ('VIRTUAL DETAIL', 'FACE TO FACE')
			AND CEM_XCHANNEL_INTERACTIONS.GLOBAL_ACTIVITY_TYPE <> 'PHONE CALL'
            THEN CEM_XCHANNEL_INTERACTIONS.INTR_ENGAG_ID
			ELSE NULL
		END
	AS INTERACTIONS_WITH_DSP,
	CASE
			WHEN BRANDS_WITH_DSP.PRDX_NK IS NOT NULL
			AND CEM_XCHANNEL_INTERACTIONS.GLOBAL_CALL_TYPE IN ('VIRTUAL DETAIL', 'FACE TO FACE')
			AND CEM_XCHANNEL_INTERACTIONS.GLOBAL_ACTIVITY_TYPE <> 'PHONE CALL' 
            THEN CEM_XCHANNEL_INTERACTIONS.INTR_ENGAG_ID
			ELSE NULL
		END
	AS INTERACTIONS_WITH_DSP_AVAILABLE,
	CASE
			WHEN DATEDIFF(
				DAY,
				INTERACTION_CALL.INCL_DT,
				DATE(INTERACTION_CALL.INCL_SUBMITTED_DT_TM)
			) <= 3  THEN CEM_XCHANNEL_INTERACTIONS.INTR_ENGAG_ID
			ELSE NULL
		END
	AS INTERACTIONS_SUBMITTED_ON_TIME,
	CASE
			WHEN DATEDIFF(
				DAY,
				INTERACTION_CALL.INCL_DT,
				DATE(INTERACTION_CALL.INCL_SUBMITTED_DT_TM)
			) <= 3  AND LEFT(INTERACTION_CALL.INCL_CALL_NM,1)='C' AND INTERACTION_CALL.INCL_SUBTYP <> 'Unplanned' AND INTERACTION_CALL.INCL_COACHING_VISIT_FLG <> 'Y' THEN INTERACTION_CALL.INCL_CALL_NM 
			ELSE NULL
		END
	AS CALLS_SUBMITTED_ON_TIME,
	CASE
		WHEN LEFT(INCL_CALL_NM,1)= 'C' THEN
			CASE
				WHEN SLSF_DESC = 'IM Cardio' AND INCL_RMT_CHNL = 'Zoom' AND INCL_SRC_SUBTYP='Other Remote Detailing Channel' AND INCL_SRC_TYP='Group Detail' THEN 2
				WHEN SLSF_DESC = 'IM&Hosp_Mix' AND INCL_RMT_CHNL = 'Zoom' AND INCL_SRC_SUBTYP='Other Remote Detailing Channel' AND INCL_SRC_TYP='Group Detail' THEN 2
				WHEN SLSF_DESC = 'Oncology' AND INCL_RMT_CHNL = 'Zoom' AND INCL_SRC_SUBTYP='Other Remote Detailing Channel' AND INCL_SRC_TYP='Group Detail' THEN 3
				WHEN SLSF_DESC = 'RD Team' AND INCL_RMT_CHNL = 'Zoom' AND INCL_SRC_SUBTYP='Other Remote Detailing Channel' AND INCL_SRC_TYP='Group Detail' THEN 3
				WHEN SLSF_DESC = 'IM Hospital' AND INCL_RMT_CHNL = 'Zoom' AND INCL_SRC_SUBTYP='Other Remote Detailing Channel' AND INCL_SRC_TYP='Group Detail' THEN 2
				WHEN SLSF_DESC = 'KAM Vaccines Team' AND INCL_RMT_CHNL = 'Zoom' AND INCL_SRC_SUBTYP='Other Remote Detailing Channel' AND INCL_SRC_TYP='Group Detail' THEN 2
				WHEN SLSF_DESC = 'HSP_Vaccines' AND INCL_RMT_CHNL = 'Zoom' AND INCL_SRC_SUBTYP='Other Remote Detailing Channel' AND INCL_SRC_TYP='Group Detail' THEN 2
				WHEN SLSF_DESC = 'SHP_Oncology' AND INCL_RMT_CHNL = 'Zoom' AND INCL_SRC_SUBTYP='Other Remote Detailing Channel' AND INCL_SRC_TYP='Group Detail' THEN 2
				WHEN SLSF_DESC = 'HSP_Cardiology' AND INCL_RMT_CHNL = 'Zoom' AND INCL_SRC_SUBTYP='Other Remote Detailing Channel' AND INCL_SRC_TYP='Group Detail' THEN 2
				WHEN INCL_SRC_SUBTYP = 'Unplanned' AND SLSF_DESC ='IM Hospital' THEN 2
				WHEN INCL_SRC_SUBTYP = 'Unplanned' AND SLSF_DESC ='HSP_Cardiology' THEN 2
				WHEN INCL_SRC_SUBTYP = 'Unplanned' AND SLSF_DESC ='IM Cardio' THEN 2
				WHEN (INCL_COACHING_VISIT_FLG= 'Y' AND SLSF_DESC IN ('IM Hospital','IM Cardio', 'HSP_Cardiology'))   THEN 1 
                WHEN INCL_COACHING_VISIT_FLG= 'Y'  THEN 2 
				ELSE 1
			END 
		WHEN LEFT(INCL_CALL_NM,1)= 'E' THEN
			CASE
				WHEN INCL_EVENT_TYP = 'Conference / Symposium' AND SLSF_DESC = 'HSP_Cardiology' THEN 2
				WHEN INCL_EVENT_TYP = 'Congress' AND SLSF_DESC = 'HSP_Cardiology' THEN 12
				WHEN INCL_EVENT_TYP = 'Representative Promotional Meeting' AND SLSF_DESC = 'HSP_Cardiology' THEN 2
				WHEN INCL_EVENT_TYP = 'Round Table Meeting-Small Scale' AND SLSF_DESC = 'HSP_Cardiology' THEN 2

				WHEN INCL_EVENT_TYP = 'Conference / Symposium' AND SLSF_DESC = 'IM Hospital' THEN 2
				WHEN INCL_EVENT_TYP = 'Congress' AND SLSF_DESC = 'IM Hospital'  THEN 12
				WHEN INCL_EVENT_TYP = 'Representative Promotional Meeting' AND SLSF_DESC = 'IM Hospital' THEN 2
				WHEN INCL_EVENT_TYP = 'Round Table Meeting-Small Scale' AND SLSF_DESC = 'IM Hospital' THEN 2

				WHEN INCL_EVENT_TYP = 'Conference / Symposium' AND SLSF_DESC = 'IM Cardio' THEN 2
				WHEN INCL_EVENT_TYP = 'Congress' AND SLSF_DESC = 'IM Cardio'  THEN 12
				WHEN INCL_EVENT_TYP = 'Representative Promotional Meeting' AND SLSF_DESC = 'IM Cardio' THEN 2
				WHEN INCL_EVENT_TYP = 'Round Table Meeting-Small Scale' AND SLSF_DESC = 'IM Cardio' THEN 2

				WHEN INCL_EVENT_TYP = 'Conference / Symposium' AND SLSF_DESC = 'IM&Hosp_Mix' THEN 2
				WHEN INCL_EVENT_TYP = 'Congress' AND SLSF_DESC = 'IM&Hosp_Mix' THEN 12
				WHEN INCL_EVENT_TYP = 'Representative Promotional Meeting' AND SLSF_DESC = 'IM&Hosp_Mix' THEN 2
				WHEN INCL_EVENT_TYP = 'Round Table Meeting-Small Scale' AND SLSF_DESC = 'IM&Hosp_Mix' THEN 2

				WHEN INCL_EVENT_TYP = 'Conference / Symposium' AND SLSF_DESC = 'SHP_Oncology' THEN 3
				WHEN INCL_EVENT_TYP = 'Congress' AND SLSF_DESC = 'SHP_Oncology' THEN 5
				WHEN INCL_EVENT_TYP = 'Representative Promotional Meeting' AND SLSF_DESC = 'SHP_Oncology' THEN 1
				WHEN INCL_EVENT_TYP = 'Round Table Meeting-Small Scale' AND SLSF_DESC = 'SHP_Oncology' THEN 2

				WHEN INCL_EVENT_TYP = 'Conference / Symposium' AND SLSF_DESC = 'Oncology' THEN 4
				WHEN INCL_EVENT_TYP = 'Congress' AND SLSF_DESC = 'Oncology' THEN 7
				WHEN INCL_EVENT_TYP = 'Representative Promotional Meeting' AND SLSF_DESC = 'Oncology' THEN 2
				WHEN INCL_EVENT_TYP = 'Round Table Meeting-Small Scale' AND SLSF_DESC = 'Oncology' THEN 3

				WHEN INCL_EVENT_TYP = 'Conference / Symposium' AND SLSF_DESC = 'RD Team' THEN 4
				WHEN INCL_EVENT_TYP = 'Congress' AND SLSF_DESC = 'RD Team' THEN 7
				WHEN INCL_EVENT_TYP = 'Representative Promotional Meeting' AND SLSF_DESC = 'RD Team' THEN 2
				WHEN INCL_EVENT_TYP = 'Round Table Meeting-Small Scale' AND SLSF_DESC = 'RD Team' THEN 3

				WHEN INCL_EVENT_TYP = 'Conference / Symposium' AND SLSF_DESC = 'HSP_Vaccines' THEN 2
				WHEN INCL_EVENT_TYP = 'Congress' AND SLSF_DESC = 'HSP_Vaccines' THEN 4
				WHEN INCL_EVENT_TYP = 'Representative Promotional Meeting' AND SLSF_DESC = 'RHSP_Vaccines' THEN 1
				WHEN INCL_EVENT_TYP = 'Round Table Meeting-Small Scale' AND SLSF_DESC = 'HSP_Vaccines' THEN 2

				WHEN INCL_EVENT_TYP = 'Conference / Symposium' AND SLSF_DESC = 'KAM Vaccines Team' THEN 3
				WHEN INCL_EVENT_TYP = 'Congress' AND SLSF_DESC = 'KAM Vaccines Team' THEN 5
				WHEN INCL_EVENT_TYP = 'Representative Promotional Meeting' AND SLSF_DESC = 'KAM Vaccines Team' THEN 1
				WHEN INCL_EVENT_TYP = 'Round Table Meeting-Small Scale' AND SLSF_DESC = 'KAM Vaccines Team' THEN 2
				
				ELSE 1
			END 
		ELSE 1
		END AS MULTIPLIER,
		CASE WHEN INTERACTION_CALL.INCL_VCC_FLG = 'N' 
			AND 
		(INTERACTION_CALL.INCL_SRC_SUBTYP IN ('Planned','Service','DO NOT USE 2') 
			Or
				(
					(INTERACTION_CALL.INCL_SRC_SUBTYP ='Unplanned' )
					And 
						
					SLSF_DESC NOT IN ('IM Hospital','HSP_Cardiology','IM Cardio')
						
				)
		)
			AND INTERACTION_CALL.INCL_COACHING_VISIT_FLG <> 'Y'  THEN INTERACTION_CALL.INCL_CALL_NM 
			ELSE NULL 
		END AS F2F_PLANNED,
    
    	--COUNT(DISTINCT CASE WHEN INTERACTION_CALL.INCL_VCC_FLG = 'N' AND ((INTERACTION_CALL.INCL_SRC_SUBTYP ='Unplanned' AND SLSF_DESC IN ('IM Hospital',
        --'HSP_Cardiology','IM Cardio')) OR INTERACTION_CALL.INCL_COACHING_VISIT_FLG = 'Y')  THEN INTERACTION_CALL.INCL_CALL_NM ELSE NULL END)*2 AS F2F_UNPLANNED,
		//F2F_UNPLANNED number should *2 on the report

CASE
  WHEN INTERACTION_CALL.INCL_VCC_FLG = 'N'
   AND (
        /* Unplanned только для 3 команд */
        (
          INTERACTION_CALL.INCL_SRC_SUBTYP = 'Unplanned'
          AND SLSF_DESC IN ('IM Hospital', 'HSP_Cardiology', 'IM Cardio')
        )
        /* Coaching для остальных команд */
        OR (
          INTERACTION_CALL.INCL_COACHING_VISIT_FLG = 'Y'
          AND SLSF_DESC NOT IN ('IM Hospital', 'HSP_Cardiology', 'IM Cardio')
        )
       )
  THEN INTERACTION_CALL.INCL_CALL_NM
  ELSE NULL
END AS F2F_UNPLANNED,

		CEM_XCHANNEL_INTERACTIONS.HCP_SK

       -- COUNT(DISTINCT CASE WHEN INTERACTION_CALL.INCL_VCC_FLG = 'N' AND INTERACTION_CALL.INCL_COACHING_VISIT_FLG <> 'Y' 
        -- AND  (INTERACTION_CALL.INCL_SRC_SUBTYP IN ('Planned','Service','DO NOT USE 2') 
       --         or  (INTERACTION_CALL.INCL_SRC_SUBTYP IN ('Unplanned') AND  SLSF_DESC NOT IN ('IM Hospital','HSP_Cardiology','IM Cardio') ) ) 
       --  THEN INTERACTION_CALL.INCL_CALL_NM ELSE NULL END)
       --   + COUNT(DISTINCT CASE WHEN INTERACTION_CALL.INCL_VCC_FLG = 'N' AND ((INTERACTION_CALL.INCL_SRC_SUBTYP ='Unplanned' AND SLSF_DESC IN ('IM Hospital',
       -- 'HSP_Cardiology','IM Cardio')) OR INTERACTION_CALL.INCL_COACHING_VISIT_FLG = 'Y')  THEN INTERACTION_CALL.INCL_CALL_NM ELSE NULL END)*2 AS F2F_TOTAL 
FROM
	COMM_GBL_PUB_PROD_DB.BI_GBL_DSHBD_CUST_ENGAGEMENT.CEM_XCHANNEL_INTERACTIONS
	INNER JOIN COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_MASTER_DATA.COUNTRY ON CEM_XCHANNEL_INTERACTIONS.CNTRY_NK = COUNTRY.CNTRY_NK
	INNER JOIN COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_HCP_INTERACTION_REPOSITORY.SALES_AREA ON CEM_XCHANNEL_INTERACTIONS.SLSA_NK = SALES_AREA.SLSA_NK
	AND COUNTRY.CNTR_CLUSTER = SALES_AREA.CNTRY_NK
	LEFT OUTER JOIN COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_HCP_INTERACTION_REPOSITORY.INTERACTION_CALL ON CEM_XCHANNEL_INTERACTIONS.SRC_CATEGORY_ID = INTERACTION_CALL.INCL_NK
	AND INTERACTION_CALL.CNTRY_NK = COUNTRY.CNTR_CLUSTER
	LEFT OUTER JOIN BRANDS_WITH_DSP ON CEM_XCHANNEL_INTERACTIONS.PRDX_NK = BRANDS_WITH_DSP.PRDX_NK
	AND BRANDS_WITH_DSP.CNTRY_NK = COUNTRY.CNTR_CLUSTER
	LEFT OUTER JOIN COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_HCP_INTERACTION_REPOSITORY.SEGMENTATION SEGMENTATION_TERR ON
	CEM_XCHANNEL_INTERACTIONS.HCPX_NK = SEGMENTATION_TERR.HCPX_NK
	AND COUNTRY.CNTR_CLUSTER = SEGMENTATION_TERR.CNTRY_NK
	AND CEM_XCHANNEL_INTERACTIONS.SLSA_NK = SEGMENTATION_TERR.SLSA_NK
	AND SEGMENTATION_TERR.SGMT_TYP = 'TERRITORY-VEEVA'
	AND SEGMENTATION_TERR.ACTIVE = 'Y'
	LEFT OUTER JOIN MCCP ON DATE(CEM_XCHANNEL_INTERACTIONS.INTR_DT_TM) BETWEEN MCCP.CPLN_ST_DT AND MCCP.CPLN_END_DT
	AND COUNTRY.CNTR_CLUSTER = MCCP.CNTRY_NK
	AND CEM_XCHANNEL_INTERACTIONS.SLSA_NK = MCCP.SLSA_NK
	AND CEM_XCHANNEL_INTERACTIONS.HCP_SK = MCCP.HCP_SK
	INNER JOIN COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_HCP_INTERACTION_REPOSITORY.SALES_FORCE SALES_FORCE ON
	SALES_AREA.SLSF_SK = SALES_FORCE.SLSF_SK
	AND SALES_AREA.CNTRY_NK = SALES_FORCE.CNTRY_NK
	LEFT OUTER JOIN COMM_GBL_PUB_PROD_DB.BI_GBL_DMART_HCP_INTERACTION_REPOSITORY.PRODUCT_XREF 
	ON CEM_XCHANNEL_INTERACTIONS.CNTRY_NK=PRODUCT_XREF.CNTRY_NK
	AND CEM_XCHANNEL_INTERACTIONS.PRDX_SK=PRODUCT_XREF.PRDX_SK
WHERE
	CEM_XCHANNEL_INTERACTIONS.CNTRY_NK IN  (
            'SI', 'HR', 'RS', 'BA', 'EE',
            'LV', 'LT', 'BG', 'UA', 'KZ'
        )
	AND 

		(
		    CEM_XCHANNEL_INTERACTIONS.GLOBAL_CALL_TYPE IN 
           (
              'VIRTUAL DETAIL',
		      'FACE TO FACE'
	       )
		)
	AND SALES_AREA.SLSA_TYPE_CD = 'TERR'	
	AND INTR_MNTH >= 202412
GROUP BY
	ALL